"""`konstant factory install-unit` (docs/LEVEL5.md 6.1): systemd --user units for the board and the
factory loop, so a factory runs for days or weeks and comes back after a reboot. konstant WRITES
the files (var/factory/systemd/konstant-board-<id>.service and konstant-factory-<id>.service) and
prints them; it never runs systemctl, never enables, starts or links a unit: the one-time
`systemctl --user link ... && systemctl --user enable --now ...` is the owner's step (howto()).

The board unit runs `bin/konstant board serve` (foreground). The factory unit runs `bin/konstant
factory run` (forever) and wants the board unit (Wants= + After=): a factory never starts
before its board. Restart=on-failure with a growing delay (RestartSec, RestartSteps,
RestartMaxDelaySec; StartLimitIntervalSec=0 never gives up) restarts a crashed loop AND a refusal
(exit 2: REVIEW L5-R2 K-13; a board that is down is not even a refusal any more: the forever loop
waits for it and, after [factory] down_after_s, tells the owner "factory down" through [notify]
mirror). Only a halt (exit 4: a notifier that could not deliver, owner action needed) is not
restarted. Stop = SIGTERM to the loop only (KillMode=mixed): it starts nothing new and lets its
running steps finish for up to TimeoutStopSec; a step cut off is picked up from the board on the
next start (factory/reconcile.py for a ship). PATH is the one `install-unit` ran with (systemd's
user PATH lacks ~/.local/bin, where a harness launcher often lives); `doctor` reports a unit file
that no longer matches what install-unit would write (`units`).
"""
from __future__ import annotations

import hashlib
import os
from pathlib import Path


def _id(cfg) -> str:
    return hashlib.sha256(os.path.realpath(cfg.home).encode()).hexdigest()[:8]


def name(cfg) -> str:
    return f"konstant-factory-{_id(cfg)}.service"


def board_name(cfg) -> str:
    return f"konstant-board-{_id(cfg)}.service"


def unit_dir(cfg) -> Path:
    return Path(cfg.home) / "var" / "factory" / "systemd"


def _path_line() -> str:
    path = os.environ.get("PATH", "")
    return f"Environment=PATH={path}" if path and "\n" not in path else ""


def board_text(cfg, path_line: str | None = None) -> str:
    home = os.path.realpath(cfg.home)
    pl = _path_line() if path_line is None else path_line
    return "\n".join([
        "# generated by `konstant factory install-unit`; konstant never enables or starts it",
        "[Unit]",
        f"Description=konstant board for {home}",
        "After=network-online.target",
        "StartLimitIntervalSec=0",
        "",
        "[Service]",
        "Type=simple",
        f"WorkingDirectory={home}",
        f"Environment=KONSTANT_HOME={home}",
        *([pl] if pl else []),
        f"ExecStart={home}/bin/konstant board serve",
        "Restart=on-failure",
        "RestartSec=10",
        "UMask=0077",
        "",
        "[Install]",
        "WantedBy=default.target",
        ""])


def text(cfg, path_line: str | None = None) -> str:
    home = os.path.realpath(cfg.home)
    pl = _path_line() if path_line is None else path_line
    board = board_name(cfg)
    return "\n".join([
        "# generated by `konstant factory install-unit`; konstant never enables or starts it",
        "[Unit]",
        f"Description=konstant factory loop for {home}",
        f"Wants={board}",
        f"After=network-online.target {board}",
        "StartLimitIntervalSec=0",
        "",
        "[Service]",
        "Type=simple",
        f"WorkingDirectory={home}",
        f"Environment=KONSTANT_HOME={home}",
        *([pl] if pl else []),
        f"ExecStart={home}/bin/konstant factory run",
        "KillMode=mixed",
        "KillSignal=SIGTERM",
        "TimeoutStopSec=900",
        "Restart=on-failure",
        "RestartSec=30",
        "RestartSteps=6",
        "RestartMaxDelaySec=900",
        "RestartPreventExitStatus=4",
        "UMask=0077",
        "",
        "[Install]",
        "WantedBy=default.target",
        ""])


def _write(p: Path, body: str) -> None:
    fd = os.open(p, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(body)


def write(cfg) -> tuple:
    """-> (factory unit path, its text); the board unit is written beside it."""
    d = unit_dir(cfg)
    d.mkdir(parents=True, exist_ok=True, mode=0o700)
    _write(d / board_name(cfg), board_text(cfg))
    p = d / name(cfg)
    body = text(cfg)
    _write(p, body)
    return p, body


def stale(cfg) -> list:
    """Unit files of this workspace that differ from what install-unit writes now (apart from
    the PATH line, which is the installing shell's): a konstant upgrade changed them."""
    out = []
    for fname, make in ((board_name(cfg), board_text), (name(cfg), text)):
        p = unit_dir(cfg) / fname
        if not p.is_file():
            continue
        have = p.read_text()
        pl = next((ln for ln in have.splitlines() if ln.startswith("Environment=PATH=")), "")
        if have != make(cfg, pl):
            out.append(fname)
    return out


def doctor_row(cfg) -> tuple:
    d = unit_dir(cfg)
    have = [n for n in (board_name(cfg), name(cfg)) if (d / n).is_file()]
    if not have:
        return ("INFO", "units", "no systemd --user units written: after a reboot start the "
                "board and the factory by hand, or `konstant factory install-unit` (then the "
                "owner's one-time `systemctl --user enable --now`)")
    old = stale(cfg) or sorted({board_name(cfg), name(cfg)} - set(have))
    if old:
        return ("WARN", "units", f"{', '.join(old)} in var/factory/systemd/ is not what this "
                "konstant writes (missing or from an "
                "older version): run `konstant factory install-unit` again, then `systemctl "
                "--user daemon-reload`")
    return ("PASS", "units", f"{board_name(cfg)} and {name(cfg)} are current (konstant never "
            "enables them; whether they are enabled is systemd's to say: `systemctl --user "
            "is-enabled`)")


def howto(path: Path) -> str:
    unit = path.name
    board = unit.replace("konstant-factory-", "konstant-board-")
    board_path = path.with_name(board)
    return (f"written: {board_path}\nwritten: {path}\n(not enabled, not started; konstant never "
            "runs systemctl)\n"
            "to run the board and the factory as your user services, once (your step):\n"
            f"  systemctl --user link {board_path} {path}\n"
            f"  systemctl --user enable --now {board} {unit}\n"
            "  loginctl enable-linger \"$USER\"   # optional: keep them running when you log out\n"
            "the factory restarts on failure (refusals included) with a growing delay; after a "
            "reboot both come back. Stop it with `bin/konstant factory stop` (drains, keeps the "
            f"kill switch set) or `systemctl --user stop {unit}`")
