"""`konstant agents sync [--check]` (DESIGN §8): the catalog rendered into the surfaces a harness
reads, inside the workspace only.

  .claude/agents/<agent>.md          agent frontmatter + role body + deliverable contract + base
                                     doctrine + the skills of its type (template agent.md.tmpl)
  .claude/skills/<skill>/SKILL.md    catalog/skills/<skill>/ copied (plus its scripts/)
  .claude/skills/workflow-<type>/    catalog/workflows/<type>.md + the phase table from types.yaml
  .claude/settings.json              workspace-scoped permissions + sandbox (agents/settings.py)
  CLAUDE.md, AGENTS.md               orchestrator doctrine, routing table, how to use konstant
  .agents/skills/<skill>/            the same skills for codex, gemini, dsh and `command` harnesses
  + each configured adapter's own files (konstant/harnesses/: .dsh/konstant.patch.yml,
    .gemini/settings.json, .gemini/konstant-policy.toml)

Only the surfaces of the CONFIGURED harnesses are written ([harness] name and the per-type
overrides; Claude Code's .claude/ + CLAUDE.md only when claude is one of them); AGENTS.md always.

Every generated Markdown file carries HEADER right after its YAML frontmatter (Claude Code needs the
frontmatter first); settings.json is JSON, which has no comments, so it carries none. `--check`
compares what is on disk with a fresh render and names every drifted, missing or stale file; a
stale file is a generated one (it carries HEADER, or sits in a generated skill dir) that the
catalog no longer produces. `sync` is the only writer; edits to generated files are overwritten.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

from konstant.agents import settings as settings_mod

HEADER = "<!-- generated by konstant agents sync from catalog/; edit the source -->"
_FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)
_PH = re.compile(r"\{\{([a-z_]+)\}\}")


class GenerateError(Exception):
    pass


def split_front(text: str, where: str) -> tuple:
    m = _FRONT.match(text)
    if not m:
        raise GenerateError(f"{where}: no YAML frontmatter (--- ... ---) at the top")
    try:
        meta = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as exc:
        raise GenerateError(f"{where}: bad frontmatter: {exc}") from exc
    if not isinstance(meta, dict):
        raise GenerateError(f"{where}: frontmatter must be a mapping")
    return meta, text[m.end():].lstrip("\n")


def fill(template: str, values: dict, where: str) -> str:
    """{{key}} placeholders, one pass: substituted text is never scanned again."""
    def sub(m):
        if m.group(1) not in values:
            raise GenerateError(f"{where}: unknown placeholder {{{{{m.group(1)}}}}}")
        return str(values[m.group(1)])
    return _PH.sub(sub, template)


_PLAIN = re.compile(r"[A-Za-z0-9][A-Za-z0-9 _.,;()/'+-]*")


def front(meta: dict) -> str:
    """YAML frontmatter: plain scalars where safe, JSON-quoted strings (valid YAML) otherwise."""
    lines = ["---"]
    for k, v in meta.items():
        v = ", ".join(v) if isinstance(v, list) else str(v)
        lines.append(f"{k}: {v if _PLAIN.fullmatch(v) else json.dumps(v)}")
    return "\n".join(lines + ["---", ""])


CLAUDE_ONLY = (".claude/", "CLAUDE.md")
SHARED_SKILLS = ".agents/skills/"
# generated files that carry no header (JSON): ours only at a fixed path (and, for a file a user
# may also keep for other reasons, only while it holds exactly what konstant generates)
HEADERLESS = (".claude/settings.json", ".gemini/settings.json")


class Generator:
    header = HEADER

    def __init__(self, cat, workspace: Path, perm: dict | None = None, python: str | None = None,
                 harness: dict | None = None, gate: dict | None = None,
                 policy: dict | None = None):
        self.cat, self.root = cat, Path(cat.root)
        self.ws, self.perm, self.python = Path(workspace), perm or {}, python
        self.hcfg = harness or {"name": "claude", "types": {}}
        self.gate, self.policy = gate or {}, policy or {}   # [gate], [board.policy] (dsh session)

    def harness_names(self) -> list:
        from konstant import harnesses
        return harnesses.configured(self.hcfg)

    def _read(self, rel: str) -> str:
        p = self.root / rel
        try:
            return p.read_text(encoding="utf-8")
        except OSError as exc:
            raise GenerateError(f"catalog/{rel}: {exc.strerror or exc}") from exc

    # --- pieces ---------------------------------------------------------------------------
    def skill_desc(self, name: str) -> str:
        meta, _ = split_front(self._read(f"skills/{name}/SKILL.md"), f"skills/{name}/SKILL.md")
        return str(meta.get("description", "")).strip()

    def skills_block(self, agent: str) -> str:
        names = self.cat.agent_skills(agent)
        if not names:
            return "(none beyond the shared doctrine)"
        return "\n".join(f"- `{n}`: {self.skill_desc(n)}" for n in names)

    def contract(self, agent: str) -> str:
        t = self.cat.type_of_agent(agent)
        if t is None:
            return ("You produce no deliverable of your own: phases produce, verifiers judge, "
                    "konstant checks. Your deliverable is the closed loop and the final report.")
        d = self.cat.types[t]["deliverable"]
        return self._read(f"doctrine/contracts/{d}.md").strip()

    def agent_body(self, agent: str) -> tuple:
        meta, body = split_front(self._read(f"agents/{agent}.md"), f"agents/{agent}.md")
        if meta.get("name") != agent:
            raise GenerateError(f"agents/{agent}.md: frontmatter name must be {agent!r}")
        if not str(meta.get("description", "")).strip():
            raise GenerateError(f"agents/{agent}.md: frontmatter needs a description")
        t = self.cat.type_of_agent(agent)
        text = fill(self._read("templates/agent.md.tmpl"), {
            "body": body.strip(), "contract": self.contract(agent),
            "base": self._read("doctrine/base.md").strip(), "skills": self.skills_block(agent),
            "type": t or "(role: drives every type)",
            "workflow": f"`workflow-{self.cat.workflow_of(t)}`" if t else "one per type",
        }, "templates/agent.md.tmpl")
        return meta, text

    def agent_prompt(self, agent: str) -> str:
        """The composed profile without frontmatter: what a phase prompt starts from."""
        return self.agent_body(agent)[1]

    def phase_table(self, t: str) -> str:
        rows = ["| # | agent | step | verdict file | parallel | runs | task |",
                "|---|---|---|---|---|---|---|"]
        for i, p in enumerate(self.cat.phases(t), 1):
            rows.append(f"| {i} | {p['agent']} | {p['step'] or '-'} | {p['verdict'] or '-'} | "
                        f"{'yes' if p['parallel'] else '-'} | "
                        f"{'only if the run changed a project file' if p['when'] else 'always'}"
                        f" | {p['task']} |")
        return "\n".join(rows)

    def workflow_skill(self, t: str) -> str:
        name = self.cat.workflow_of(t)
        meta, body = split_front(self._read(f"workflows/{name}.md"), f"workflows/{name}.md")
        spec = self.cat.types[t]
        desc = str(meta.get("description") or spec["summary"]).strip()
        return front({"name": f"workflow-{t}", "description": desc}) + HEADER + "\n" + fill(
            self._read("templates/skill.md.tmpl"), {
                "type": t, "agent": spec["agent"], "deliverable": spec["deliverable"],
                "summary": spec["summary"], "phases": self.phase_table(t), "body": body.strip(),
                "read_only": "yes" if self.cat.read_only(t) else "no",
                "close": "`job review` into `reviewed`" if self.cat.is_review_type(t)
                         else "`job close` + `konstant verify` into `verified`",
            }, "templates/skill.md.tmpl")

    def routing_table(self) -> str:
        rows = ["| type | agent | deliverable | workflow skill | closes by |",
                "|---|---|---|---|---|"]
        for t in self.cat.type_names():
            spec = self.cat.types[t]
            rows.append(f"| `{t}` | `{spec['agent']}` | {spec['deliverable']} | "
                        f"`workflow-{t}` | {'review' if self.cat.is_review_type(t) else 'verify'} |")
        return "\n".join(rows)

    def top_doc(self, tmpl: str) -> str:
        _, orch = split_front(self._read("agents/orchestrator.md"), "agents/orchestrator.md")
        return HEADER + "\n" + fill(self._read(f"templates/{tmpl}"), {
            "workspace": str(self.ws), "routing": self.routing_table(),
            "orchestrator": orch.strip(), "base": self._read("doctrine/base.md").strip(),
            "types": ", ".join(f"`{t}`" for t in self.cat.type_names()),
            "operate": self._read("templates/operate.md.tmpl").strip(),
            **self._agents_md_paths(),
        }, f"templates/{tmpl}")

    def _agents_md_paths(self) -> dict:
        claude = "claude" in self.harness_names()
        src = "its source is `catalog/agents/<agent>.md` (role) with the shared doctrine below"
        if claude:
            return {"profiles": "the composed profile for each agent (role, deliverable contract, "
                    f"shared doctrine, skills) is `.claude/agents/<agent>.md`; {src}.",
                    "skills_dir": ".claude/skills/"}
        return {"profiles": "each agent's role is `catalog/agents/<agent>.md`, with the shared "
                "doctrine below and the deliverable contract of its type in "
                "`catalog/doctrine/contracts/`; a headless phase gets the composed profile in its "
                "prompt.", "skills_dir": ".agents/skills/"}

    # --- the whole render -----------------------------------------------------------------
    def skill_files(self, prefix: str) -> dict:
        out: dict = {}
        for name in sorted(p.name for p in (self.root / "skills").iterdir() if p.is_dir()):
            src = self.root / "skills" / name
            meta, body = split_front(self._read(f"skills/{name}/SKILL.md"),
                                     f"skills/{name}/SKILL.md")
            if meta.get("name") != name or not str(meta.get("description", "")).strip():
                raise GenerateError(f"skills/{name}/SKILL.md: frontmatter needs name: {name} "
                                    "and a description")
            out[f"{prefix}{name}/SKILL.md"] = front(meta) + HEADER + "\n" + body
            for f in sorted(src.rglob("*")):
                if f.is_file() and f.name != "SKILL.md" and "__pycache__" not in f.parts:
                    out[f"{prefix}{name}/{f.relative_to(src)}"] = f.read_text(encoding="utf-8")
        for t in self.cat.type_names():
            out[f"{prefix}workflow-{t}/SKILL.md"] = self.workflow_skill(t)
        return out

    def render_claude(self) -> dict:
        out: dict = {}
        for agent in self.cat.agents():
            meta, text = self.agent_body(agent)
            keep = {k: meta[k] for k in ("name", "description", "tools", "model") if k in meta}
            out[f".claude/agents/{agent}.md"] = front(keep) + HEADER + "\n" + text
        out.update(self.skill_files(".claude/skills/"))
        try:
            out[".claude/settings.json"] = settings_mod.render(self.ws, self.perm, self.python)
        except settings_mod.SettingsError as exc:
            raise GenerateError(str(exc)) from exc
        out["CLAUDE.md"] = self.top_doc("CLAUDE.md.tmpl")
        return out

    def render_by_harness(self, only: str | None = None) -> dict:
        """{harness name: {workspace-relative path: content}} for the configured harnesses
        (`only`: just that one). A shared file appears under every harness that reads it."""
        from konstant import harnesses
        names = self.harness_names()
        if only is not None:
            if only not in names:
                raise GenerateError(f"harness {only!r} is not configured ([harness] name or a "
                                    f"[harness.types.<type>] row); configured: {', '.join(names)}")
            names = [only]
        agents_md = self.top_doc("AGENTS.md.tmpl")
        shared = None
        out: dict = {}
        for name in names:
            files = {"AGENTS.md": agents_md}
            if name == "claude":
                files.update(self.render_claude())
            else:
                shared = shared if shared is not None else self.skill_files(SHARED_SKILLS)
                files.update(shared)
                files.update(harnesses.adapter(name).files(self, self.hcfg))
            out[name] = files
        return out

    def render(self, only: str | None = None) -> dict:
        """{workspace-relative path: content} for every generated file."""
        out: dict = {}
        for files in self.render_by_harness(only).values():
            out.update(files)
        return out

    def _ours_on_disk(self) -> set:
        """Generated files on disk: AGENTS.md / CLAUDE.md, every file under .claude/agents with
        HEADER, every file in a .claude/skills or .agents/skills dir whose SKILL.md carries HEADER,
        an adapter file that carries HEADER, and the headerless JSON files (HEADERLESS)."""
        from konstant.harnesses.gemini import settings_json
        found = {p for p in ("CLAUDE.md", "AGENTS.md", ".claude/settings.json")
                 if (self.ws / p).is_file()}
        gem = self.ws / ".gemini" / "settings.json"
        if gem.is_file() and gem.read_text(encoding="utf-8", errors="replace") == settings_json():
            found.add(".gemini/settings.json")
        for f in (".dsh/konstant.patch.yml", ".dsh/konstant-session.patch.yml",
                  ".dsh/konstant-gate.mjs", ".gemini/konstant-policy.toml"):
            if _has_header(self.ws / f):
                found.add(f)
        dsh_agents = self.ws / ".dsh" / "agents"
        if dsh_agents.is_dir():
            found |= {f".dsh/agents/{p.name}" for p in dsh_agents.glob("*.md") if _has_header(p)}
        agents = self.ws / ".claude" / "agents"
        if agents.is_dir():
            found |= {f".claude/agents/{p.name}" for p in agents.glob("*.md") if _has_header(p)}
        for root in (self.ws / ".claude" / "skills", self.ws / ".agents" / "skills"):
            if root.is_dir():
                for d in root.iterdir():
                    if d.is_dir() and _has_header(d / "SKILL.md"):
                        found |= {str(f.relative_to(self.ws)) for f in d.rglob("*")
                                  if f.is_file() and "__pycache__" not in f.parts}
        return found

    def _owned(self, rel: str, only: str | None) -> bool:
        """With `only` (one harness), stale detection is limited to that harness's paths."""
        if only is None:
            return True
        if only == "claude":
            return rel.startswith(CLAUDE_ONLY)
        prefixes = {"dsh": (".dsh/",), "gemini": (".gemini/",)}.get(only, ())
        return rel.startswith((SHARED_SKILLS,) + prefixes)

    def check(self, only: str | None = None) -> list:
        want = self.render(only)
        lines = []
        for rel, text in want.items():
            p = self.ws / rel
            if not p.is_file():
                lines.append(f"missing: {rel}")
            elif p.read_text(encoding="utf-8", errors="replace") != text:
                lines.append(f"drifted: {rel}")
        lines += [f"stale: {rel}" for rel in sorted(self._ours_on_disk() - set(want))
                  if self._owned(rel, only)]
        return lines

    def sync(self, only: str | None = None) -> list:
        want = self.render(only)
        changed = []
        for rel in sorted(r for r in self._ours_on_disk() - set(want) if self._owned(r, only)):
            p = self.ws / rel
            p.unlink()
            changed.append(f"removed: {rel}")
            while p.parent != self.ws and not any(p.parent.iterdir()):
                p = p.parent
                p.rmdir()
        for rel, text in want.items():
            p = self.ws / rel
            if p.is_file() and p.read_text(encoding="utf-8", errors="replace") == text:
                continue
            p.parent.mkdir(parents=True, exist_ok=True)
            tmp = p.with_name(p.name + ".tmp")
            tmp.write_text(text, encoding="utf-8")
            tmp.replace(p)
            changed.append(f"wrote: {rel}")
        return changed


def _has_header(p: Path) -> bool:
    try:
        with open(p, encoding="utf-8", errors="replace") as fh:
            return HEADER in fh.read(4096)
    except OSError:
        return False
