"""`konstant factory install-unit` (docs/LEVEL5.md 6.1): a systemd --user unit for the factory loop,
so a factory can run for days or weeks and come back after a restart. konstant WRITES the file
(var/factory/systemd/konstant-factory-<id>.service) and prints it; it never runs systemctl,
never enables, starts or links the unit: that is the owner's step.

The unit runs `bin/konstant factory run` (forever) in the workspace. systemd's stop sends SIGTERM to
the loop only (KillMode=mixed): it starts nothing new and lets its running steps finish (graceful
drain) for up to TimeoutStopSec, then systemd kills what is left; a step cut off that way is
picked up from the board on the next start (factory/reconcile.py for a ship). Restart=on-failure
restarts a crashed loop, but not a refusal (exit 2: kill switch, halt, no jail) or a halt (4).
"""
from __future__ import annotations

import hashlib
import os
from pathlib import Path


def name(cfg) -> str:
    h = hashlib.sha256(os.path.realpath(cfg.home).encode()).hexdigest()[:8]
    return f"konstant-factory-{h}.service"


def text(cfg) -> str:
    home = os.path.realpath(cfg.home)
    return "\n".join([
        "# generated by `konstant factory install-unit`; konstant never enables or starts it",
        "[Unit]",
        f"Description=konstant factory loop for {home}",
        "After=network-online.target",
        "",
        "[Service]",
        "Type=simple",
        f"WorkingDirectory={home}",
        f"Environment=KONSTANT_HOME={home}",
        f"ExecStart={home}/bin/konstant factory run",
        "KillMode=mixed",
        "KillSignal=SIGTERM",
        "TimeoutStopSec=900",
        "Restart=on-failure",
        "RestartSec=30",
        "RestartPreventExitStatus=2 4",
        "UMask=0077",
        "",
        "[Install]",
        "WantedBy=default.target",
        ""])


def write(cfg) -> tuple:
    d = Path(cfg.home) / "var" / "factory" / "systemd"
    d.mkdir(parents=True, exist_ok=True, mode=0o700)
    p = d / name(cfg)
    body = text(cfg)
    fd = os.open(p, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(body)
    return p, body


def howto(path: Path) -> str:
    unit = path.name
    return (f"written: {path} (not enabled, not started; konstant never runs systemctl)\n"
            "to run the factory as your user service (your step):\n"
            f"  systemctl --user link {path}\n"
            f"  systemctl --user enable --now {unit}\n"
            "stop it with `bin/konstant factory stop` (drains, keeps the kill switch set) or "
            f"`systemctl --user stop {unit}`")
