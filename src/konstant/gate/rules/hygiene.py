"""Rule `hygiene` (thresholds from `[gate] hygiene`, recorded in the run record).

OUT:     a non-test source file under OUT over `hard` (400) lines needs `reason` in its first 5.
project: a source file the run changed in the project's git tree (vs the run base) that GREW past
         `grown` (600) lines without a `reason` in its first 5 lines is UNMET. A file that did not
         grow is grandfathered: the rule fails a run only for growth it caused.
"""
from __future__ import annotations

import os

from konstant.gate.rules.common import (Finding, Run, blob_text, git_top, has_run_dir, inside,
                                        out_files, worktree_drift)

SRC_EXT = (".py", ".pyx", ".sh", ".bash", ".zsh", ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx",
           ".vue", ".svelte", ".c", ".h", ".cc", ".cpp", ".hpp", ".m", ".cs", ".fs", ".lua",
           ".go", ".rs", ".rb", ".php", ".java", ".kt", ".scala", ".swift", ".dart", ".zig",
           ".ex", ".exs")
VENDOR_DIRS = {"node_modules", "vendor", "vendored", "third_party", "third-party", "dist",
               "build", "obj"}
GENERATED_NAMES = (".min.js", "_pb2.py", "_pb2_grpc.py", ".pb.go", ".d.ts", ".g.cs")
GENERATED_MARKS = ("@generated", "do not edit", "auto-generated", "autogenerated", "generated by")
DEFAULTS = {"target": 250, "hard": 400, "tests": 600, "grown": 600}


def is_source(rel: str) -> bool:
    low = rel.lower().replace(os.sep, "/")
    parts = low.split("/")
    return (low.endswith(SRC_EXT) and not low.endswith(GENERATED_NAMES)
            and ".generated." not in parts[-1] and not set(parts[:-1]) & VENDOR_DIRS)


def is_test(rel: str) -> bool:
    parts = rel.replace(os.sep, "/").split("/")
    fn = parts[-1]
    return (any(p in ("test", "tests") for p in parts[:-1]) or fn.startswith("test_")
            or fn.endswith(("_test.py", "_test.go", "_test.rs")) or ".test." in fn
            or ".spec." in fn)


def _lines(path):
    try:
        with open(path, encoding="utf-8", errors="ignore") as fh:
            return fh.readlines()
    except OSError:
        return None


def _head_says(lines, words) -> bool:
    head = "".join(lines[:5]).lower()
    return any(w in head for w in words)


def _lines_at(top, base, rel) -> int:
    text = blob_text(top, base, rel)
    return text.count("\n") + (1 if text and not text.endswith("\n") else 0)


def check(run: Run) -> list:
    lim = {**DEFAULTS, **(run.gate.get("hygiene") or {})}
    out = []
    if run.out.is_dir():
        for f in out_files(run.out):
            rel = os.path.relpath(f, run.out)
            if not is_source(rel) or is_test(rel):
                continue
            lines = _lines(f)
            if lines is not None and len(lines) > lim["hard"] and not _head_says(lines, ("reason",)):
                out.append(Finding("hygiene", f"{rel} is {len(lines)} lines (> {lim['hard']}) with "
                                              "no 'reason' in its first 5 lines - split it by "
                                              "concern or state the reason", owner="producer"))
    base, project = run.rec.get("git_base"), run.project
    top = git_top(project) if project and project.is_dir() else None
    if not (top and base):
        return out
    for rel in worktree_drift(top, base):
        full = os.path.join(top, rel)
        if (not is_source(rel) or has_run_dir(rel) or inside(full, run.out)
                or not os.path.isfile(full)):
            continue
        lines = _lines(full)
        if (lines is None or len(lines) <= lim["grown"] or _head_says(lines, GENERATED_MARKS)
                or _head_says(lines, ("reason",))):
            continue
        before = _lines_at(top, base, rel)
        if len(lines) > before:
            out.append(Finding("hygiene", f"{rel} grew to {len(lines)} lines (was {before} at the "
                                          f"run base) with no 'reason' in its first 5 lines - over "
                                          f"{lim['grown']} fails file hygiene", owner="producer"))
    return out
